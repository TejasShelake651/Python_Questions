import numpy as np

a = np.array([[1, 2], [3, 4]])
b = np.array([[5, 6], [7, 8]])

# Addition
print("Addition:")
print(a + b)

# Subtraction
print("Subtraction:")
print(a - b)

# Multiplication
print("Multiplication:")
print(a * b)

# Division
print("Division:")
print(a / b)

# Transpose
print("Transpose:")
print(a.T)

# Exponential
print("Exponential:")
print(np.exp(a))